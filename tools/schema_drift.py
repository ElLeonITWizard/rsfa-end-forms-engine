#!/usr/bin/env python3
"""Monday schema drift: the documented Make 8731317 result-key contract vs a live board column export, by column ID.

Classifies every contract column as unchanged, display-name change (same ID, new title), real type change, or removed,
lists live columns missing from the contract, and lists the manifests whose data keys are affected. Schema only:
IDs, titles, types and labels; never item values.

Usage: python3 tools/schema_drift.py --contract .local/reference/8731317_result_key_contract.tsv \\
          --board .local/reference/masterboard-columns-<date>.json --date <YYYY-MM-DD> --out docs/generated/monday-schema-drift.md
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
# The contract file uses Monday's legacy API type names; these pairs are the same type, not a change.
TYPE_ALIASES = {("boolean", "checkbox"), ("numeric", "numbers"), ("board", "board_relation"), ("color", "status")}


def norm(k: str) -> str:
    return k.replace("/", "_").replace(".", "_")


def manifest_keys(m: dict) -> set[str]:
    keys = set()
    for f in m.get("fields", []):
        s = f.get("source", {})
        keys |= {s.get("key"), (s.get("when") or {}).get("key")}
    keys |= {o.get("source", {}).get("key") for o in m.get("overlays", [])}
    for r in m.get("validation", {}).get("requires", []):
        keys |= {r.get("ifPresent"), (r.get("when") or {}).get("key"), (r.get("require") or {}).get("key")}
    return {k for k in keys if k}


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--contract", required=True, type=Path)
    p.add_argument("--board", required=True, type=Path)
    p.add_argument("--date", required=True)
    p.add_argument("--out", required=True, type=Path)
    a = p.parse_args(argv)
    rows = [r for r in csv.DictReader(a.contract.open(encoding="utf-8"), delimiter="\t") if r["source"] == "column"]
    board = json.loads(a.board.read_text(encoding="utf-8"))["board"]
    live = {c["id"]: c for c in board["columns"]}
    unchanged, renamed, retyped, removed = [], [], [], []
    for r in rows:
        c = live.get(r["monday_column_id"])
        if c is None:
            replacement = [x for x in board["columns"] if x["title"] == r["result_key"]]
            removed.append((r, replacement[0] if replacement else None))
            continue
        hint = r["monday_type_hint"]
        if hint != c["type"] and (hint, c["type"]) not in TYPE_ALIASES:
            retyped.append((r, c))
        if c["title"] != r["result_key"]:
            renamed.append((r, c))
        elif hint == c["type"] or (hint, c["type"]) in TYPE_ALIASES:
            unchanged.append(r)
    contract_ids = {r["monday_column_id"] for r in rows}
    new = [c for c in board["columns"] if c["id"] not in contract_ids and c["id"] != "name"]
    titles = [c["title"] for c in board["columns"]]
    dups = sorted({t for t in titles if titles.count(t) > 1})
    changed_keys = {norm(r["result_key"]) for r, _ in renamed} | {norm(r["result_key"]) for r, rep in removed if rep is None}
    affected = []
    for mp in sorted((REPO / "mappings").rglob("*.json")):
        hit = sorted(manifest_keys(json.loads(mp.read_text(encoding="utf-8"))) & changed_keys)
        if hit:
            affected.append((mp.relative_to(REPO).as_posix(), hit))
    out = [f"# Monday schema drift (generated {a.date})", "",
           f"Board `{board['id']}` \"{board['name']}\" ({len(live)} columns) vs the documented `8731317` result-key "
           f"contract ({len(rows)} column keys). Generated by `tools/schema_drift.py`; schema only (IDs, titles, types), "
           "never item values. Do not edit by hand.", "",
           "| Classification | Count |", "|---|---|",
           f"| Same ID, same title, same type (legacy API type names such as `boolean`/`numeric` count as the same type) | {len(unchanged)} |",
           f"| **Display-name change** (same ID, new title) | {len(renamed)} |",
           f"| **Real type change** (same ID) | {len(retyped)} |",
           f"| **Column removed** (ID gone) | {len(removed)} |",
           f"| Live column not in the contract snapshot | {len(new)} |",
           f"| Live duplicate titles (would be merged into arrays by `8731317`) | {len(dups)} |", "",
           "## Display-name changes (same column ID)", "",
           "`8731317` builds each result key from the column's **live title** (module 8: `key = col.title || col.id`), "
           "so a display-name change changes the key that MacroForge and the engine receive.", "",
           "| Column ID | Contract key (old title) | Live title | Type |", "|---|---|---|---|"]
    out += [f"| `{c['id']}` | {r['result_key']} | **{c['title']}** | {c['type']} |" for r, c in renamed]
    out += ["", "## Real type changes", ""] + ([f"- `{c['id']}`: {r['monday_type_hint']} → {c['type']}" for r, c in retyped] or ["None."])
    out += ["", "## Removed columns (ID no longer on the board)", "", "| Removed ID | Contract key | Live column with the same title |",
            "|---|---|---|"]
    def replacement(r, rep):
        if rep is None:
            return "**none: key no longer sent**"
        same = r["monday_type_hint"] == rep["type"] or (r["monday_type_hint"], rep["type"]) in TYPE_ALIASES
        return (f"`{rep['id']}` ({rep['type']}) — same key, new column"
                + ("" if same else f"; **value type changed: {r['monday_type_hint']} → {rep['type']}**"))
    out += [f"| `{r['monday_column_id']}` | {r['result_key']} | {replacement(r, rep)} |" for r, rep in removed]
    out += ["", "## Live columns not in the contract snapshot", "", "| Column ID | Title | Type |", "|---|---|---|"]
    out += [f"| `{c['id']}` | {c['title']} | {c['type']} |" for c in new]
    out += ["", "## Committed manifests reading a changed or removed key", ""]
    out += [f"- `{p}`: " + ", ".join(f"`{k}`" for k in ks) for p, ks in affected] or ["None."]
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"drift report written: {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
